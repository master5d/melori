const TTS_URL = "https://api.fish.audio/v1/tts";

export function buildTtsRequest({
  apiKey,
  model,
  refId,
  text,
  format = "wav",
  latency = "normal",
}) {
  return {
    url: TTS_URL,
    headers: {
      Authorization: `Bearer ${apiKey}`,
      "Content-Type": "application/json",
      model,
    },
    body: JSON.stringify({ text, reference_id: refId, format, latency }),
  };
}
